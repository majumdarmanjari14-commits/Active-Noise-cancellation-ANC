import numpy as np
import matplotlib.pyplot as plt

fs, f = 8000, 200                      # sample rate, a 200 Hz "hum"
t = np.arange(0, 0.02, 1/fs)
noise = np.sin(2*np.pi*f*t)

# Part 1: perfect anti-noise vs anti-noise that is 20° late
fig, ax = plt.subplots(1, 2, figsize=(11, 3.5))
for a, phi in zip(ax, [0, 20]):
    anti = -np.sin(2*np.pi*f*t - np.deg2rad(phi))
    a.plot(t*1000, noise, label='noise')
    a.plot(t*1000, anti, label='anti-noise')
    a.plot(t*1000, noise + anti, 'k', lw=2, label='what you hear')
    a.set_title(f"phase error = {phi}°"); a.set_xlabel("ms"); a.legend()
plt.tight_layout(); plt.show()

# Part 2: how much cancellation do you get for each phase error?
phis = np.linspace(0.5, 120, 500)
residual = np.abs(2*np.sin(np.deg2rad(phis)/2))      # leftover amplitude
plt.plot(phis, 20*np.log10(residual))
plt.axhline(0, color='r', ls='--', label='no ANC (0 dB)')
plt.xlabel("phase error (degrees)"); plt.ylabel("noise change (dB)")
plt.title("Cancellation vs phase error"); plt.legend(); plt.grid(); plt.show()